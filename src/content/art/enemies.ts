function shellFrame(shift: number): string {
  const rows = ['....kkkkkkkk....', '..kkppppppppkk..', '.kppppppppppppk.', 'kppppppppppppppk', 'kppppppppppppppk', 'kppppppppppppppk', 'kppppppppppppppk', '.kppppppppppppk.', '..kkppppppppkk..', '....kkkkkkkk....'];
  return rows
    .map((row, y) => row.split('').map((c, x) => (c === 'p' ? ((x * 2 + y + shift) % 7 < 2 ? 'P' : (x + y * 2 + shift) % 9 === 0 ? 'w' : 'p') : c)).join(''))
    .join('\n');
}

