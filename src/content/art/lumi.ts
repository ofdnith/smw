/** Paleta por poder: a capa muda de cor para leitura instantânea. */
export function lumiDef(power: Power): { palette: Palette } {
  switch (power) {
    case 'shell': return { palette: { ...LUMI_PALETTE, y: '#f7d56a', Y: '#d9ad2c' } };
    case 'leaf': return { palette: { ...LUMI_PALETTE, y: '#8fd14f', Y: '#5f9a2d' } };
    case 'lantern': return { palette: { ...LUMI_PALETTE, y: '#5fb4e8', Y: '#2f7fb3' } };
    default: return { palette: LUMI_PALETTE };
  }
}

